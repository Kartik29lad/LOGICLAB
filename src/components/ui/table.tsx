export type TableColumn<T> = { key: keyof T; label: string };
export function Table<T extends Record<string, React.ReactNode>>({
  columns,
  rows,
}: Readonly<{ columns: TableColumn<T>[]; rows: T[] }>) {
  return (
    <div className="table-wrap">
      <table>
        <thead>
          <tr>
            {columns.map((column) => (
              <th key={String(column.key)}>{column.label}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, index) => (
            <tr key={index}>
              {columns.map((column) => (
                <td key={String(column.key)}>{row[column.key]}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
